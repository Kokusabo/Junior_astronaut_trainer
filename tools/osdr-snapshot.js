// Builds data/osdr-studies.js from a saved NASA OSDR search result, so the game has real study data
// even when the browser cannot read osdr.nasa.gov directly (opened from file://).
// 1. Open https://osdr.nasa.gov/osdr/data/search?term=spaceflight&type=cgene&size=25 and save it as
//    data/osdr-search-spaceflight.json
// 2. Run: node tools/osdr-snapshot.js
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'data', 'osdr-search-spaceflight.json');
const out = path.join(__dirname, '..', 'data', 'osdr-studies.js');
const json = JSON.parse(fs.readFileSync(src, 'utf8'));
// Keep only what the game uses, in the same shape the live API returns, so one parser handles both.
const hits = json.hits.hits.map((h) => ({
  _source: {
    Accession: h._source.Accession,
    'Study Title': h._source['Study Title'],
    Mission: { Name: (h._source.Mission && h._source.Mission.Name) || '' },
  },
}));
const saved = fs.statSync(src).mtime.toISOString().slice(0, 10);
const body = `// Generated by tools/osdr-snapshot.js from data/osdr-search-spaceflight.json. Do not edit by hand.
// Source: NASA Open Science Data Repository (OSDR), https://osdr.nasa.gov/osdr/data/search?term=spaceflight&type=cgene&size=25
// Saved: ${saved}. ${hits.length} studies.
const OSDR_SNAPSHOT = ${JSON.stringify({ saved, hits: { hits } }, null, 1)};

if (typeof module !== 'undefined') module.exports = OSDR_SNAPSHOT;
`;
fs.writeFileSync(out, body);
console.log(`Wrote ${out}: ${hits.length} studies, saved ${saved}.`);
