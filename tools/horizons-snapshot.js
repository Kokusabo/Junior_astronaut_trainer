// Builds data/horizons-moon.js: a saved copy of the real Earth-Moon distance (JPL Horizons) for the next
// 60 days, used when the browser cannot reach JPL live.
// Run: node tools/horizons-snapshot.js
// (If Node cannot verify the certificate on this machine, run with
//  NODE_EXTRA_CA_CERTS=/etc/ssl/certs/ca-certificates.crt node tools/horizons-snapshot.js)
const fs = require('fs');
const path = require('path');
const Moon = require('../src/moon.js');

const day = (d) => d.toISOString().slice(0, 10);
const start = new Date();
const stop = new Date(start.getTime() + 60 * 864e5);
const url = Moon.horizonsUrl(day(start), day(stop));

fetch(url)
  .then((r) => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); })
  .then((json) => {
    const days = Moon.parseHorizons(json);
    if (days.length < 7) throw new Error(`only ${days.length} days`);
    const out = path.join(__dirname, '..', 'data', 'horizons-moon.js');
    fs.writeFileSync(out, `// Generated by tools/horizons-snapshot.js. Do not edit by hand.
// Source: NASA JPL Horizons, Moon (301) seen from Earth's centre (500@399), daily range.
// ${url}
const HORIZONS_SNAPSHOT = ${JSON.stringify({ saved: day(new Date()), days })};

if (typeof module !== 'undefined') module.exports = HORIZONS_SNAPSHOT;
`);
    console.log(`Wrote ${out}: ${days.length} days, ${Math.min(...days.map((d) => d.km))}-${Math.max(...days.map((d) => d.km))} km.`);
  })
  .catch((e) => { console.error(`Failed: ${e.message}`); process.exit(1); });
