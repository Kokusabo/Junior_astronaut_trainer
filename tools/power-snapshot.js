// Builds data/power-ksc.js: a saved copy of real NASA POWER daily weather at Kennedy Space Center,
// used when the browser cannot reach NASA POWER live (offline, or opened from file:// with blocked requests).
// Run: node tools/power-snapshot.js
// (If Node cannot verify NASA's certificate on this machine, run with
//  NODE_EXTRA_CA_CERTS=/etc/ssl/certs/ca-certificates.crt node tools/power-snapshot.js)
const fs = require('fs');
const path = require('path');
const Weather = require('../src/weather.js');

const ymd = (d) => d.toISOString().slice(0, 10).replace(/-/g, '');
const end = new Date(Date.now() - 4 * 864e5); // NASA POWER lags a few days behind today
const start = new Date(end - 60 * 864e5);
const url = Weather.powerUrl(ymd(start), ymd(end));

fetch(url)
  .then((r) => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); })
  .then((json) => {
    const days = Weather.parsePower(json);
    if (days.length < 7) throw new Error(`only ${days.length} usable days`);
    const p = json.properties.parameter;
    const keep = { properties: { parameter: { WS10M_MAX: p.WS10M_MAX, PRECTOTCORR: p.PRECTOTCORR, T2M: p.T2M } } };
    const out = path.join(__dirname, '..', 'data', 'power-ksc.js');
    fs.writeFileSync(out, `// Generated by tools/power-snapshot.js. Do not edit by hand.
// Source: NASA POWER daily API, Kennedy Space Center (${Weather.KSC.lat} N, ${Weather.KSC.lon} E).
// ${url}
// Saved: ${new Date().toISOString().slice(0, 10)}. ${days.length} days.
const POWER_SNAPSHOT = ${JSON.stringify({ saved: new Date().toISOString().slice(0, 10), ...keep })};

if (typeof module !== 'undefined') module.exports = POWER_SNAPSHOT;
`);
    console.log(`Wrote ${out}: ${days.length} days, ${days.filter((d) => d.go).length} GO.`);
  })
  .catch((e) => { console.error(`Failed: ${e.message}`); process.exit(1); });
