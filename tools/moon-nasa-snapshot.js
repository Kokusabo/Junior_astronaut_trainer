// Builds data/moon-nasa.js: saved NASA data for Mission 2, used when the game cannot reach NASA live.
//  - epic: the newest EPIC photo of the whole Earth (DSCOVR satellite), as a small picture
//  - flare: the strongest solar flare of the last 30 days (NASA DONKI, CCMC)
//  - asteroid: the closest asteroid flyby of the last 30 days (NASA JPL close-approach data)
//  - terrain: a real north-south elevation profile through each landing site (NASA LRO LOLA, via Moon Trek)
// Run: node tools/moon-nasa-snapshot.js
// (If Node cannot verify NASA's certificate on this machine, run with
//  NODE_EXTRA_CA_CERTS=/etc/ssl/certs/ca-certificates.crt node tools/moon-nasa-snapshot.js)
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const Moon = require('../src/moon.js');
const { MOON_SITES } = require('../src/moon-data.js');

const day = (d) => new Date(Date.now() - d * 864e5).toISOString().slice(0, 10);
const json = async (u) => { const r = await fetch(u); if (!r.ok) throw new Error(`HTTP ${r.status} ${u}`); return r.json(); };
const bytes = async (u) => { const r = await fetch(u); if (!r.ok) throw new Error(`HTTP ${r.status} ${u}`); return Buffer.from(await r.arrayBuffer()); };

// Minimal PNG reader for 8-bit, non-interlaced images (Moon Trek tiles are 8-bit grey + alpha).
function readPng(buf) {
  let pos = 8, w = 0, h = 0, type = 0;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos), kind = buf.toString('ascii', pos + 4, pos + 8), body = buf.subarray(pos + 8, pos + 8 + len);
    if (kind === 'IHDR') { w = body.readUInt32BE(0); h = body.readUInt32BE(4); type = body[9]; if (body[8] !== 8 || body[12] !== 0) throw new Error('only 8-bit, non-interlaced PNG'); }
    if (kind === 'IDAT') idat.push(body);
    pos += 12 + len;
  }
  const ch = { 0: 1, 2: 3, 4: 2, 6: 4 }[type];
  if (!ch) throw new Error(`PNG colour type ${type} not supported`);
  const raw = zlib.inflateSync(Buffer.concat(idat)), stride = w * ch, out = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= ch ? out[y * stride + x - ch] : 0, b = y ? out[(y - 1) * stride + x] : 0, c = x >= ch && y ? out[(y - 1) * stride + x - ch] : 0;
      const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
      const pred = [0, a, b, (a + b) >> 1, pa <= pb && pa <= pc ? a : pb <= pc ? b : c][f];
      out[y * stride + x] = (src[x] + pred) & 255;
    }
  }
  return { w, h, grey: (x, y) => out[y * stride + x * ch] };
}

// LOLA elevation tiles (equirectangular, zoom 5 = 16384 x 8192 px for the whole Moon, about 0.67 km per px).
const TREK = 'https://trek.nasa.gov/tiles/Moon/EQ/LRO_LOLA_DEM_Global_128ppd_v04/1.0.0//default/default028mm/5';
const tiles = new Map();
async function greyAt(lat, lon) {
  const W = 16384, H = 8192, x = Math.floor(((lon + 180) / 360) * W) % W, y = Math.min(H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * H)));
  const key = `${y >> 8}/${x >> 8}`;
  if (!tiles.has(key)) tiles.set(key, readPng(await bytes(`${TREK}/${key}.png`)));
  return tiles.get(key).grey(x & 255, y & 255);
}
// 64 samples along a 1.4 degree (about 42 km) north-south line through the site (kept inside the pole).
async function profile(site) {
  const top = Math.min(89.9, site.lat + 0.7), bottom = Math.max(-89.9, top - 1.4), out = [];
  for (let i = 0; i < 64; i++) out.push(await greyAt(top - ((top - bottom) * i) / 63, site.lon));
  return out;
}

(async () => {
  const data = { saved: day(0) };
  const epic = Moon.epicLatest(await json(Moon.EPIC_URL));
  if (!epic) throw new Error('EPIC: no image');
  data.epic = { date: epic.date, lat: epic.lat, lon: epic.lon, image: `data:image/jpeg;base64,${(await bytes(epic.url)).toString('base64')}` };
  data.flare = Moon.strongestFlare(await json(Moon.donkiUrl(day(30), day(0))));
  data.asteroid = Moon.closestApproach(await json(Moon.cadUrl(day(30), day(0))));
  data.terrain = {};
  for (const s of MOON_SITES) data.terrain[s.id] = await profile(s);
  const out = path.join(__dirname, '..', 'data', 'moon-nasa.js');
  fs.writeFileSync(out, `// Generated by tools/moon-nasa-snapshot.js. Do not edit by hand.
// Sources: NASA EPIC (DSCOVR), NASA DONKI (CCMC), NASA JPL close-approach data, NASA LRO LOLA via Moon Trek.
// terrain: 64 elevation samples (8-bit grey, about 78 m per step) along 42 km north-south through each site.
const MOON_NASA = ${JSON.stringify(data)};

if (typeof module !== 'undefined') module.exports = MOON_NASA;
`);
  console.log(`Wrote ${out} (${Math.round(fs.statSync(out).size / 1024)} KB). EPIC ${data.epic.date}, flare ${data.flare && data.flare.classType}, asteroid ${data.asteroid && data.asteroid.name} at ${data.asteroid && data.asteroid.km} km.`);
  for (const [id, p] of Object.entries(data.terrain)) console.log(id.padEnd(12), 'grey', Math.min(...p), '-', Math.max(...p));
})().catch((e) => { console.error('Snapshot failed:', e.message); process.exit(1); });
