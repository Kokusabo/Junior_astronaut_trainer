// Builds data/earth-maps.js: saved NASA GIBS world maps for the Earth seen on the flight to the Moon.
// day: Blue Marble (land and ocean), night: Black Marble (city lights), clouds: one day of MODIS Terra
// true-colour photos. The game fetches newer clouds live and falls back to this copy when offline.
// Run: node tools/earth-snapshot.js
// (If Node cannot verify NASA's certificate on this machine, run with
//  NODE_EXTRA_CA_CERTS=/etc/ssl/certs/ca-certificates.crt node tools/earth-snapshot.js)
const fs = require('fs');
const path = require('path');
const Moon = require('../src/moon.js');

const date = new Date(Date.now() - 864e5).toISOString().slice(0, 10); // yesterday: a full day of swaths
const jobs = { day: Moon.gibsUrl('BlueMarble_NextGeneration'), night: Moon.gibsUrl('VIIRS_Black_Marble'), clouds: Moon.gibsUrl('MODIS_Terra_CorrectedReflectance_TrueColor', date) };

(async () => {
  const maps = { saved: date };
  for (const [k, url] of Object.entries(jobs)) {
    const r = await fetch(url);
    if (!r.ok || !String(r.headers.get('content-type')).startsWith('image/jpeg')) throw new Error(`${k}: HTTP ${r.status} ${r.headers.get('content-type')}`);
    maps[k] = `data:image/jpeg;base64,${Buffer.from(await r.arrayBuffer()).toString('base64')}`;
  }
  const out = path.join(__dirname, '..', 'data', 'earth-maps.js');
  fs.writeFileSync(out, `// Generated by tools/earth-snapshot.js. Do not edit by hand.
// Source: NASA GIBS (gibs.earthdata.nasa.gov), 512x256 world maps. Clouds: MODIS Terra, ${date}.
const EARTH_MAPS = ${JSON.stringify(maps)};

if (typeof module !== 'undefined') module.exports = EARTH_MAPS;
`);
  console.log(`Wrote ${out} (${Math.round(fs.statSync(out).size / 1024)} KB, clouds ${date})`);
})().catch((e) => { console.error('Earth snapshot failed:', e.message); process.exit(1); });
